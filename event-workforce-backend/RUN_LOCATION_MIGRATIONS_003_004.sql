CREATE INDEX IF NOT EXISTS location_districts_state_idx
    ON public.location_districts (state_id, is_active);
CREATE INDEX IF NOT EXISTS location_areas_district_idx
    ON public.location_areas (district_id, is_active);

ALTER TABLE public.location_states ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.location_districts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.location_areas ENABLE ROW LEVEL SECURITY;

