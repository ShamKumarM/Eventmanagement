-- Combined location schema update for AbiHub.
-- Safe to run after 001_jobs_schema.sql and 002_role_selection_rpc.sql.
-- It combines 003_job_location_dropdowns.sql + 004_worker_preferred_location.sql.
-- The statements are idempotent; run this in the Supabase project used by Render.

-- Run this migration in Supabase SQL Editor before deploying the updated API.
-- Job creators now select State -> District -> Area. Coordinates remain optional
-- backend-managed columns and are no longer accepted in the job-create request.

ALTER TABLE public.jobs
    ADD COLUMN IF NOT EXISTS state text,
    ADD COLUMN IF NOT EXISTS district text;

-- Preserve existing job locations when migrating older records.
UPDATE public.jobs
SET state = COALESCE(NULLIF(state, ''), 'Tamil Nadu'),
    district = COALESCE(NULLIF(district, ''), NULLIF(city, ''), 'Coimbatore')
WHERE state IS NULL OR district IS NULL;

ALTER TABLE public.jobs
    ALTER COLUMN state SET NOT NULL,
    ALTER COLUMN district SET NOT NULL;

CREATE TABLE IF NOT EXISTS public.location_states (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE,
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS public.location_districts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    state_id bigint NOT NULL REFERENCES public.location_states(id) ON DELETE CASCADE,
    name text NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    UNIQUE (state_id, name)
);

CREATE TABLE IF NOT EXISTS public.location_areas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    district_id bigint NOT NULL REFERENCES public.location_districts(id) ON DELETE CASCADE,
    name text NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    UNIQUE (district_id, name)
);

INSERT INTO public.location_states (name)
VALUES ('Tamil Nadu')
ON CONFLICT (name) DO NOTHING;

INSERT INTO public.location_districts (state_id, name)
SELECT id, 'Coimbatore'
FROM public.location_states
WHERE name = 'Tamil Nadu'
ON CONFLICT (state_id, name) DO NOTHING;

